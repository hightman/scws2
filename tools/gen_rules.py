#!/usr/bin/env python3
"""Compile the two UTF-8 rule data files into committed, dependency-free C tables."""
import argparse
import hashlib
from pathlib import Path
import unicodedata

ROOT = Path(__file__).resolve().parents[1]
ALLOWED = {'chnum0': '0０零〇', 'chnum1': '一二三四五六七八九十百千两兩万萬亿億兆',
           'chnum2': '123456789１２３４５６７８９', 'chnum3': '.．点點',
           'chnum4': '壹贰貳叁參肆伍陆陸柒捌玖拾佰仟', 'chnum5': '第每'}
SECTIONS = ('symbol', *ALLOWED, 'munit')


def width(ch):
    value = ord(ch)
    return value - 0xfee0 if 0xff01 <= value <= 0xff5e else value


def parse(text):
    groups, current = {}, None
    for number, line in enumerate(text.splitlines(), 1):
        line = line.strip()
        if not line or line.startswith(';'):
            continue
        if line.startswith('[') and line.endswith(']'):
            current = line[1:-1]
            if current not in SECTIONS or current in groups:
                raise ValueError(f'invalid/repeated section at line {number}')
            groups[current] = set()
        else:
            if current is None or any(c.isspace() or unicodedata.category(c).startswith('C') for c in line):
                raise ValueError(f'invalid entry at line {number}')
            if current == 'munit':
                if len(line) > 16:
                    raise ValueError('unit exceeds 16 Unicode scalars')
                groups[current].add(tuple(map(width, line)))
            else:
                if current == 'symbol' and any(unicodedata.category(c)[0] in 'LN' for c in line):
                    raise ValueError('symbol entries must not contain letters or numbers')
                if current in ALLOWED and any(c not in ALLOWED[current] for c in line):
                    raise ValueError(f'unknown numeric character in {current}')
                groups[current].update(map(width, line))
    if set(groups) != set(SECTIONS) or any(not entries for entries in groups.values()):
        raise ValueError('all eight supported sections must be present and nonempty')
    return groups


def generate(root=ROOT):
    merged = {name: set() for name in SECTIONS}
    fingerprint = hashlib.sha256()
    for name in ('rules.ini', 'rules_cht.ini'):
        data = (root / 'etc' / name).read_bytes()
        fingerprint.update(name.encode() + b'\0' + data)
        for section, values in parse(data.decode('utf-8')).items():
            merged[section].update(values)
    lines = ['/* Generated by tools/gen_rules.py; edit etc/rules*.ini, then make rules. */',
             '/* Source SHA-256: ' + fingerprint.hexdigest() + ' */',
             '#ifndef SCWS_RULES_DATA_H', '#define SCWS_RULES_DATA_H', '#include <stdint.h>']
    for section in SECTIONS[:-1]:
        values = ', '.join(hex(ch) for ch in sorted(merged[section]))
        lines.append(f'static const uint32_t rule_{section}[] = {{ {values}, 0 }};')
    units = sorted(merged['munit'])
    maximum = max(map(len, units))
    lines.append(f'static const uint32_t rule_units[][{maximum + 1}] = {{')
    for unit in units:
        lines.append('\t{ ' + ', '.join(hex(ch) for ch in unit) + ', 0 },')
    lines.extend(['\t{ 0 }', '};', '#endif', ''])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = ROOT / 'src/rules_data.h'
    try:
        content = generate()
        if args.check:
            if output.read_text(encoding='utf-8') != content:
                raise ValueError('generated rule tables are stale; run make rules')
        else:
            output.write_text(content, encoding='utf-8')
    except (OSError, UnicodeError, ValueError) as error:
        parser.exit(1, f'ERROR: {error}\n')


if __name__ == '__main__':
    main()
